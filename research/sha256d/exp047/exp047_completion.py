#!/usr/bin/env python3
"""EXP-047 completion campaign driver.

Executes the unexecuted remainder of the original EXP-047
design (EXP047_REPORT.md sections 3.2 and 3.3) under the
corrected S-C criterion predeclared in
EXP047_COMPLETION_REPORT.md sections 1 to 4:

- S-A batch_search hit sets: exact set equality with the
  hashlib reference on all 30 predeclared cases, all six
  backends, with seam stats pinned, verification_failures 0
  and no rescan on every call.
- S-B raw flagged pairs (five native backends) and the
  EXP-022 flags-library pairs (v512, v512dual engines):
  exact hit sets and per-pair digest equality.
- S-C search_first_counted under the corrected criterion:
  (a) found-flag agreement with the reference, (b) hit
  genuineness (in-span, digest equals cpu_digest, digest
  meets target), (c) minimum identity recorded as a
  statistic per backend, never pass/fail.
- Gate 3 G1 to G16 as campaign items.

Cases are generated by the original driver's gen_cases()
imported unchanged (seed 47047), so every header, start,
count and target is byte-identical to the original design.

Any found-flag disagreement, false hit, false miss or wrong
digest stops the campaign at once, writes
RAW_RESULTS/completion_mismatch.json plus a minimal repro,
and exits 3. Production code is never modified. Nothing
here times anything for a result.

Usage: python3 exp047_completion.py
"""

import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, REPO)
sys.path.insert(0, HERE)

import exp047_fuzz as orig  # noqa: E402  (case generation only)
from gpu.engine import ComputeEngine, cpu_digest  # noqa: E402

RESULTS = os.path.join(HERE, "RAW_RESULTS")
os.makedirs(RESULTS, exist_ok=True)
PROGRESS = os.path.join(RESULTS, "completion_progress.jsonl")

GENESIS = orig.GENESIS
GENESIS_NONCE = orig.GENESIS_NONCE
NONCE_SPACE = orig.NONCE_SPACE
MAX_BATCH = orig.MAX_BATCH
DIFF1 = orig.DIFF1
T_D8 = orig.T_D8


def log(obj):
    obj = dict(obj)
    obj["t"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    with open(PROGRESS, "a") as f:
        f.write(json.dumps(obj) + "\n")
    print(json.dumps(obj), flush=True)


class CampaignFailure(Exception):
    def __init__(self, kind, detail):
        super().__init__(kind)
        self.kind = kind
        self.detail = detail


def fail(kind, detail):
    raise CampaignFailure(kind, detail)


def write_mismatch(kind, detail):
    rec = {"kind": kind, "detail": detail,
           "t": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    with open(os.path.join(RESULTS, "completion_mismatch.json"),
              "w") as f:
        json.dump(rec, f, indent=1)
    log({"phase": "MISMATCH", **rec})
    hdr = detail.get("header_hex")
    backend = detail.get("backend")
    if hdr and backend:
        repro = (
            "#!/usr/bin/env python3\n"
            "\"\"\"Minimal repro for the EXP-047 completion "
            "mismatch in\ncompletion_mismatch.json. Run from "
            "the repo root. Replays the failing\nsurface call "
            "and prints the reference expectation beside the "
            "observed\nresult.\"\"\"\n"
            "import os, sys\n"
            "sys.path.insert(0, os.path.abspath(os.path.join(\n"
            "    os.path.dirname(__file__), '..', '..', "
            "'..')))\n"
            "from gpu.engine import ComputeEngine, cpu_digest\n"
            f"HEADER = bytes.fromhex({hdr!r})\n"
            f"START = {detail.get('start')}\n"
            f"COUNT = {detail.get('count')}\n"
            f"TARGET = {detail.get('target')}\n"
            f"BACKEND = {backend!r}\n"
            "eng = ComputeEngine(requested=BACKEND)\n"
            "want = set()\n"
            "for i in range(COUNT):\n"
            "    d = cpu_digest(HEADER, START + i)\n"
            "    if int.from_bytes(d, 'little') <= TARGET:\n"
            "        want.add(START + i)\n"
            "print('reference hits:', len(want),\n"
            "      'minimum:', None if not want else min(want))\n"
            "cands, st = eng.batch_search(HEADER, TARGET, "
            "START, COUNT)\n"
            "print('batch_search hits:', len(cands),\n"
            "      'stats backend:', st.get('backend'),\n"
            "      'verification_failures:',\n"
            "      st.get('verification_failures'),\n"
            "      'rescanned:', st.get('rescanned'))\n"
            "hit, _a, _s = eng.search_first_counted(\n"
            "    HEADER, TARGET, START, COUNT)\n"
            "print('search_first_counted:', hit)\n")
        with open(os.path.join(
                RESULTS, "completion_minimal_repro.py"),
                "w") as f:
            f.write(repro)


def ref_hits(hdr, target, start, count):
    hits = set()
    for i in range(count):
        d = cpu_digest(hdr, start + i)
        if int.from_bytes(d, "little") <= target:
            hits.add(start + i)
    return hits


def build_engines():
    specs = {}
    for name in ("v512dual", "v512", "shani", "avx2", "c",
                 "cpu"):
        eng = ComputeEngine(requested=name)
        if eng.backend != name:
            fail("engine_selection", {
                "backend": name, "selected": eng.backend,
                "reason": "pinned request did not select the "
                          "tier"})
        specs[name] = eng
    native = {
        "c": lambda e: (e._c_lib, e._c_batch,
                        e._c_batch_flagged),
        "avx2": lambda e: (e._a_lib, e._a_batch,
                           e._a_batch_flagged),
        "shani": lambda e: (e._m_lib, e._m_batch,
                            e._m_batch_flagged),
        "v512": lambda e: (e._v_lib, e._v_batch,
                           e._v_batch_flagged),
        "v512dual": lambda e: (e._vd_lib, e._vd_batch,
                               e._vd_batch_flagged),
    }
    return specs, native


def check_sc(eng, name, cid, hdr, target, start, count, want,
             sc_stats, sc_calls):
    """One S-C call under the corrected criterion."""
    hit, _att, _sec = eng.search_first_counted(
        hdr, target, start, count)
    rec = sc_stats[name]
    entry = {"case": cid, "found": hit is not None,
             "returned": None if hit is None else hit[0],
             "ref_minimum": None if not want else min(want),
             "is_minimum": None, "offset": None}
    if want and hit is None:
        fail("search_first_found_flag", {
            "backend": name, "case": cid,
            "header_hex": hdr.hex(), "start": start,
            "count": count, "target": target,
            "nonce": min(want),
            "reason": "returned no hit where the reference "
                      "set is non-empty (false miss)"})
    if not want and hit is not None:
        fail("search_first_found_flag", {
            "backend": name, "case": cid,
            "header_hex": hdr.hex(), "start": start,
            "count": count, "target": target, "nonce": hit[0],
            "reason": "reported a hit where the reference "
                      "set is empty (false hit)"})
    if hit is not None:
        nonce, digest = hit
        if not (start <= nonce < start + count):
            fail("search_first_genuineness", {
                "backend": name, "case": cid,
                "header_hex": hdr.hex(), "start": start,
                "count": count, "target": target,
                "nonce": nonce,
                "reason": "returned nonce outside the span"})
        if digest != cpu_digest(hdr, nonce):
            fail("search_first_genuineness", {
                "backend": name, "case": cid,
                "header_hex": hdr.hex(), "start": start,
                "count": count, "target": target,
                "nonce": nonce,
                "reason": "returned digest differs from "
                          "cpu_digest",
                "expected": cpu_digest(hdr, nonce).hex(),
                "actual": digest.hex()})
        if int.from_bytes(digest, "little") > target:
            fail("search_first_genuineness", {
                "backend": name, "case": cid,
                "header_hex": hdr.hex(), "start": start,
                "count": count, "target": target,
                "nonce": nonce,
                "reason": "returned digest does not meet the "
                          "target (false hit)"})
        entry["is_minimum"] = (nonce == min(want))
        entry["offset"] = nonce - min(want)
        if entry["is_minimum"]:
            rec["minimum_returns"] += 1
        else:
            rec["nonminimum_genuine_returns"] += 1
    rec["calls"] += 1
    rec["records"].append(entry)
    sc_calls += 1
    return sc_calls


def phase_search(engines, native, cases, sc_stats):
    per_backend = {}
    surface_checks = 0
    sc_calls = 0
    observed_hits = {}
    for (cid, tname, target, hdr, start, count, s_c) in cases:
        want = ref_hits(hdr, target, start, count)
        observed_hits[cid] = len(want)
        for name, eng in engines.items():
            rec = per_backend.setdefault(
                name, {"batch_search_calls": 0, "nonces": 0,
                       "flagged_calls": 0, "flags_calls": 0})
            cands, st = eng.batch_search(hdr, target, start,
                                         count)
            rec["batch_search_calls"] += 1
            rec["nonces"] += count
            got_set = {c["nonce"] for c in cands}
            if st.get("backend") != name \
                    or st.get("verification_failures") != 0 \
                    or st.get("rescanned"):
                fail("search_surface", {
                    "backend": name, "case": cid,
                    "header_hex": hdr.hex(), "start": start,
                    "count": count, "target": target,
                    "reason": "batch_search stats not pinned, "
                              "or verification failures, or a "
                              "rescan",
                    "stats_backend": st.get("backend"),
                    "verification_failures":
                        st.get("verification_failures"),
                    "rescanned": st.get("rescanned")})
            if got_set != want:
                extra = sorted(got_set - want)
                missing = sorted(want - got_set)
                fail("search_hitset_batch_search", {
                    "backend": name, "case": cid,
                    "header_hex": hdr.hex(), "start": start,
                    "count": count, "target": target,
                    "nonce": (extra or missing)[0],
                    "extra": extra[:8], "missing": missing[:8]})
            surface_checks += 1
            if name in native:
                lib, _b, flag_fn = native[name](eng)
                pairs = flag_fn(lib, hdr, target, start, count)
                if pairs is None:
                    fail("search_refusal", {
                        "backend": name, "case": cid,
                        "header_hex": hdr.hex(), "start": start,
                        "count": count, "target": target,
                        "reason": "flagged batch returned None "
                                  "on a valid span"})
                rec["flagged_calls"] += 1
                fset = {n for n, _d in pairs}
                if fset != want:
                    extra = sorted(fset - want)
                    missing = sorted(want - fset)
                    fail("search_hitset_flagged", {
                        "backend": name, "case": cid,
                        "header_hex": hdr.hex(), "start": start,
                        "count": count, "target": target,
                        "nonce": (extra or missing)[0],
                        "extra": extra[:8],
                        "missing": missing[:8]})
                for n, d in pairs:
                    if d != cpu_digest(hdr, n):
                        fail("search_flagged_digest", {
                            "backend": name, "case": cid,
                            "header_hex": hdr.hex(), "nonce": n,
                            "expected": cpu_digest(hdr, n).hex(),
                            "actual": d.hex()})
                surface_checks += 1
                if name in ("v512", "v512dual") \
                        and eng._vf_lib is not None:
                    vpairs = eng._vf_batch_flagged(
                        eng._vf_lib, hdr, target, start, count)
                    if vpairs is None:
                        fail("search_refusal", {
                            "backend": name + "/flags",
                            "case": cid,
                            "header_hex": hdr.hex(),
                            "start": start, "count": count,
                            "target": target,
                            "reason": "flags batch returned "
                                      "None on a valid span"})
                    rec["flags_calls"] += 1
                    vset = {n for n, _d in vpairs}
                    if vset != want:
                        extra = sorted(vset - want)
                        missing = sorted(want - vset)
                        fail("search_hitset_flags", {
                            "backend": name + "/flags",
                            "case": cid,
                            "header_hex": hdr.hex(),
                            "start": start, "count": count,
                            "target": target,
                            "nonce": (extra or missing)[0],
                            "extra": extra[:8],
                            "missing": missing[:8]})
                    for n, d in vpairs:
                        if d != cpu_digest(hdr, n):
                            fail("search_flags_digest", {
                                "backend": name + "/flags",
                                "case": cid,
                                "header_hex": hdr.hex(),
                                "nonce": n,
                                "expected":
                                    cpu_digest(hdr, n).hex(),
                                "actual": d.hex()})
                    surface_checks += 1
            if s_c:
                sc_calls = check_sc(eng, name, cid, hdr, target,
                                    start, count, want,
                                    sc_stats, sc_calls)
        log({"phase": "search", "case": cid, "target": tname,
             "count": count, "ref_hits": len(want)})
    # S_FIRST_BOUNDARY under the corrected criterion.
    b1_want = ref_hits(GENESIS, orig.T_FULL, NONCE_SPACE - 1, 1)
    b2_want = ref_hits(GENESIS, DIFF1, GENESIS_NONCE - 3, 1000)
    for name, eng in engines.items():
        sc_calls = check_sc(eng, name, "S_FIRST_BOUNDARY-1",
                            GENESIS, orig.T_FULL,
                            NONCE_SPACE - 1, 1, b1_want,
                            sc_stats, sc_calls)
        sc_calls = check_sc(eng, name, "S_FIRST_BOUNDARY-2",
                            GENESIS, DIFF1, GENESIS_NONCE - 3,
                            1000, b2_want, sc_stats, sc_calls)
    log({"phase": "search_boundary",
         "boundary_ref_hits": {"S_FIRST_BOUNDARY-1":
                               len(b1_want),
                               "S_FIRST_BOUNDARY-2":
                               len(b2_want)},
         "sc_calls_total_all_backends": sc_calls})
    return {"per_backend": per_backend,
            "surface_checks": surface_checks,
            "search_first_calls_total": sc_calls,
            "observed_reference_hits": observed_hits}


def phase_gate3(engines, native):
    hdr = GENESIS
    results = {}
    cases = [
        ("G1", lambda e: e.batch_search(hdr[:79], T_D8, 0, 16)),
        ("G2", lambda e: e.batch_search(hdr + b"x", T_D8, 0,
                                        16)),
        ("G3", lambda e: e.batch_search(hdr, 0, 0, 16)),
        ("G4", lambda e: e.batch_search(hdr, 1 << 256, 0, 16)),
        ("G5", lambda e: e.batch_search(hdr, -1, 0, 16)),
        ("G6", lambda e: e.batch_search(hdr, T_D8, -1, 16)),
        ("G7", lambda e: e.batch_search(hdr, T_D8, 0, 0)),
        ("G8", lambda e: e.batch_search(hdr, T_D8, 0, -5)),
        ("G9", lambda e: e.batch_search(hdr, T_D8, 0,
                                        MAX_BATCH + 1)),
        ("G10", lambda e: e.batch_search(hdr, T_D8,
                                         NONCE_SPACE - 100,
                                         200)),
        ("G11", lambda e: e.batch_search(hdr, T_D8,
                                         NONCE_SPACE, 1)),
        ("G12", lambda e: e.search_first_counted(
            hdr, T_D8, NONCE_SPACE - 100, 200)),
        ("G13", lambda e: e.search_first_counted(hdr, 0, 0,
                                                 16)),
        ("G14", lambda e: e.search_first_counted(hdr[:79],
                                                 T_D8, 0, 16)),
    ]
    for name, eng in engines.items():
        rec = {}
        for cid, fn in cases:
            try:
                fn(eng)
                rec[cid] = "NO_RAISE"
            except Exception as exc:  # noqa: BLE001
                rec[cid] = type(exc).__name__
        results[name] = rec
        log({"phase": "gate3", "engine": name, "results": rec})
    lib_results = {}
    for name, eng in engines.items():
        if name not in native:
            continue
        lib, batch_fn, flag_fn = native[name](eng)
        pairs = flag_fn(lib, hdr, T_D8, NONCE_SPACE - 8, 16)
        digs = batch_fn(lib, hdr, T_D8, NONCE_SPACE - 8, 16)
        lib_results[name] = {
            "G15_flagged_crossing": "refused" if pairs is None
            else f"NOT_REFUSED ({len(pairs)} pairs)",
            "G16_batch_crossing": "refused" if digs is None
            else "NOT_REFUSED",
        }
        log({"phase": "gate3_lib", "engine": name,
             "results": lib_results[name]})
    deviations = []
    for name, rec in results.items():
        for cid, outcome in rec.items():
            if outcome != "ValueError":
                deviations.append({"engine": name, "case": cid,
                                   "observed": outcome,
                                   "expected": "ValueError"})
    for name, rec in lib_results.items():
        for cid, outcome in rec.items():
            if outcome != "refused":
                deviations.append({"engine": name, "case": cid,
                                   "observed": outcome,
                                   "expected": "refused"})
    return {"seam": results, "library": lib_results,
            "deviations": deviations,
            "verdict": "PASS" if not deviations else "FAIL"}


def main():
    cpu_model = "unknown"
    with open("/proc/cpuinfo") as f:
        for line in f:
            if line.startswith("model name"):
                cpu_model = line.split(":", 1)[1].strip()
                break
    _batch_cases, search_cases = orig.gen_cases()
    predeclared = {
        "search_nonces_per_backend":
            sum(c for _i, _t, _tg, _h, _s, c, _f
                in search_cases),
        "search_cases": len(search_cases),
        "search_first_calls_per_backend":
            sum(1 for c in search_cases if c[6]) + 2,
    }
    engines, native = build_engines()
    sc_stats = {}
    for name, eng in engines.items():
        desc = eng.describe()
        sc_stats[name] = {
            "c_threads": desc.get("c_threads"),
            "calls": 0, "minimum_returns": 0,
            "nonminimum_genuine_returns": 0, "records": []}
    manifest = {
        "experiment": "EXP-047 completion",
        "seed": orig.SEED,
        "host_cpu": cpu_model,
        "started": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                 time.gmtime()),
        "predeclared": predeclared,
        "engines": {name: eng.describe()
                    for name, eng in engines.items()},
        "flags_lib_loaded": {
            name: (eng._vf_lib is not None)
            for name, eng in engines.items()},
        "targets": {"T_FULL": orig.T_FULL, "T_D8": orig.T_D8,
                    "T_D16": orig.T_D16, "T_D24": orig.T_D24,
                    "T_SOLO": orig.T_SOLO,
                    "T_ZERO": orig.T_ZERO},
    }
    with open(os.path.join(RESULTS, "completion_manifest.json"),
              "w") as f:
        json.dump(manifest, f, indent=1)
    log({"phase": "start", "predeclared": predeclared})

    out = {"manifest": "completion_manifest.json"}
    try:
        out["search"] = phase_search(engines, native,
                                     search_cases, sc_stats)
    except CampaignFailure as cf:
        write_mismatch(cf.kind, cf.detail)
        out["search"] = {"FAILED": cf.kind, "detail": cf.detail}
        out["sc_statistics"] = sc_stats
        with open(os.path.join(
                RESULTS, "completion_search_results.json"),
                "w") as f:
            json.dump(out, f, indent=1)
        sys.exit(3)
    out["sc_statistics"] = {
        name: {k: v for k, v in rec.items() if k != "records"}
        for name, rec in sc_stats.items()}
    out["sc_records"] = {name: rec["records"]
                         for name, rec in sc_stats.items()}
    with open(os.path.join(
            RESULTS, "completion_search_results.json"),
            "w") as f:
        json.dump(out["search"], f, indent=1)
    with open(os.path.join(
            RESULTS, "completion_sc_statistics.json"),
            "w") as f:
        json.dump({"statistics": out["sc_statistics"],
                   "records": out["sc_records"]}, f, indent=1)
    log({"phase": "search_done"})

    out["gate3"] = phase_gate3(engines, native)
    with open(os.path.join(RESULTS,
                           "completion_gate3_results.json"),
              "w") as f:
        json.dump(out["gate3"], f, indent=1)
    out["finished"] = time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                    time.gmtime())
    with open(os.path.join(RESULTS, "completion_summary.json"),
              "w") as f:
        json.dump({k: v for k, v in out.items()
                   if k != "sc_records"}, f, indent=1)
    log({"phase": "COMPLETE",
         "gate3_verdict": out["gate3"]["verdict"]})


if __name__ == "__main__":
    main()
